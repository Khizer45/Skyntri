from __future__ import annotations

import uuid
from pathlib import Path

from fastapi import HTTPException, UploadFile, status

from app.core.config import settings


# ============================================================
# Upload configuration
# ============================================================

ALLOWED_CONTENT_TYPES = {
    "image/jpeg": ".jpg",
    "image/png": ".png",
    "image/webp": ".webp",
}

MAX_FILE_SIZE_BYTES = 10 * 1024 * 1024  # 10 MB


# ============================================================
# Helpers
# ============================================================

def _get_safe_extension(file: UploadFile) -> str:
    """
    Return a safe extension based on the validated MIME type.

    We do not trust the extension supplied by the client because
    filenames are user-controlled.
    """

    extension = ALLOWED_CONTENT_TYPES.get(
        file.content_type or ""
    )

    if extension is None:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail=(
                "Unsupported format. "
                "Please upload JPEG, PNG, or WebP."
            ),
        )

    return extension


def _validate_subfolder(subfolder: str) -> str:
    """
    Validate the internal upload subfolder.

    Upload subfolders are application-controlled values such as:
        analyses
        avatars
        progress
        ingredients_scans
        reports
    """

    if not subfolder:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Upload destination is invalid.",
        )

    # Only allow a single directory name.
    # This prevents ../ path traversal.
    candidate = Path(subfolder)

    if (
        candidate.name != subfolder
        or subfolder in {".", ".."}
        or "/" in subfolder
        or "\\" in subfolder
    ):
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Invalid upload destination.",
        )

    return subfolder


# ============================================================
# Main upload function
# ============================================================

def save_upload(
    file: UploadFile,
    subfolder: str,
) -> str:
    """
    Validate and save an uploaded image.

    Returns:
        Public application URL such as:

        /uploads/analyses/<uuid>.jpg

    Security:
        - MIME type is validated.
        - Extension is generated by the server.
        - Filename is UUID-based.
        - Maximum file size is enforced while streaming.
        - Failed/oversized files are removed.
        - User-supplied filenames are never used as filesystem paths.
    """

    if file is None:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="Please upload an image.",
        )

    if not file.filename:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The uploaded file has no filename.",
        )

    # --------------------------------------------------------
    # Validate MIME type
    # --------------------------------------------------------

    extension = _get_safe_extension(file)

    # --------------------------------------------------------
    # Validate internal destination
    # --------------------------------------------------------

    safe_subfolder = _validate_subfolder(
        subfolder
    )

    # --------------------------------------------------------
    # Create destination directory
    # --------------------------------------------------------

    dest_dir = (
        settings.upload_path
        / safe_subfolder
    )

    dest_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    # --------------------------------------------------------
    # Generate server-controlled filename
    # --------------------------------------------------------

    filename = (
        f"{uuid.uuid4().hex}"
        f"{extension}"
    )

    dest = dest_dir / filename

    # Defensive check:
    # ensure generated destination remains inside upload directory.
    upload_root = settings.upload_path.resolve()
    destination_resolved = dest.resolve()

    try:
        destination_resolved.relative_to(
            upload_root
        )
    except ValueError as exc:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="The upload destination is invalid.",
        ) from exc

    # --------------------------------------------------------
    # Stream file to disk
    # --------------------------------------------------------

    size = 0
    chunk_size = 1024 * 1024  # 1 MB

    try:
        with dest.open("wb") as buffer:
            while True:
                chunk = file.file.read(
                    chunk_size
                )

                if not chunk:
                    break

                size += len(chunk)

                if size > MAX_FILE_SIZE_BYTES:
                    raise HTTPException(
                        status_code=status.HTTP_400_BAD_REQUEST,
                        detail=(
                            "Image exceeds the 10MB size limit."
                        ),
                    )

                buffer.write(chunk)

    except HTTPException:
        # Remove incomplete/oversized file.
        try:
            dest.unlink(missing_ok=True)
        except OSError:
            pass

        raise

    except OSError as exc:
        # Remove partially written file.
        try:
            dest.unlink(missing_ok=True)
        except OSError:
            pass

        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="The image could not be saved.",
        ) from exc

    except Exception as exc:
        # Defensive cleanup for unexpected failures.
        try:
            dest.unlink(missing_ok=True)
        except OSError:
            pass

        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail="The image upload could not be completed.",
        ) from exc

    # --------------------------------------------------------
    # Reject empty uploads
    # --------------------------------------------------------

    if size == 0:
        try:
            dest.unlink(missing_ok=True)
        except OSError:
            pass

        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail="The uploaded image is empty.",
        )

    # --------------------------------------------------------
    # Return public URL
    # --------------------------------------------------------

    return (
        f"/uploads/"
        f"{safe_subfolder}/"
        f"{filename}"
    )